const dictionaries = {
  'zh-CN': Object.fromEntries(messages.map(([key, zh]) => [key, zh])),
  ms: Object.fromEntries(messages.map(([key, , ms]) => [key, ms])),
};

export function translate(locale: Locale, key: string, values: TranslationValues = {}): string {
  const text = locale === 'en' ? key : dictionaries[locale][key] ?? key;
  return text.replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match));
}

export const LOCALE_STORAGE_KEY = 'learning-path-engine:locale';
export function readLocale(storage: Pick<Storage, 'getItem'> | null): Locale {
  try {
    const locale = storage?.getItem(LOCALE_STORAGE_KEY);
    return locale === 'zh-CN' || locale === 'ms' ? locale : 'en';
  } catch { return 'en'; }
}
